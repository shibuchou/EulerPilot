#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${ROOT:-$(cd "$SCRIPT_DIR/../.." && pwd)}"

LATENCY_WEIGHT="${LATENCY_WEIGHT:-1000}"
BACKGROUND_WEIGHT="${BACKGROUND_WEIGHT:-20}"
BATCH_WEIGHT="${BATCH_WEIGHT:-100}"
EULERPILOT_CPU_PSI_THRESHOLD="${EULERPILOT_CPU_PSI_THRESHOLD:-0.05}"
EULERPILOT_LATENCY_WAIT_THRESHOLD_NS="${EULERPILOT_LATENCY_WAIT_THRESHOLD_NS:-500000}"
EULERPILOT_BACKGROUND_RUNTIME_THRESHOLD_NS="${EULERPILOT_BACKGROUND_RUNTIME_THRESHOLD_NS:-2500000}"
INTERVAL_MS="${INTERVAL_MS:-1000}"
STRESS_WORKERS="${STRESS_WORKERS:-2}"
WRK_THREADS="${WRK_THREADS:-2}"
WRK_CONNECTIONS="${WRK_CONNECTIONS:-32}"
WRK_DURATION="${WRK_DURATION:-10s}"
BACKEND="${BACKEND:-cgroup_v2}"
ACTIVE_PREFIX="${ACTIVE_PREFIX:-active_noisy}"

printf '[INFO] Nginx 正式主实验启动\n'
printf '[INFO] latency_weight=%s background_weight=%s batch_weight=%s cpu_psi_threshold=%s latency_wait_threshold_ns=%s background_runtime_threshold_ns=%s\n' \
    "$LATENCY_WEIGHT" "$BACKGROUND_WEIGHT" "$BATCH_WEIGHT" "$EULERPILOT_CPU_PSI_THRESHOLD" "$EULERPILOT_LATENCY_WAIT_THRESHOLD_NS" "$EULERPILOT_BACKGROUND_RUNTIME_THRESHOLD_NS"
printf '[INFO] wrk_threads=%s wrk_connections=%s wrk_duration=%s stress_workers=%s interval_ms=%s backend=%s active_prefix=%s\n' \
    "$WRK_THREADS" "$WRK_CONNECTIONS" "$WRK_DURATION" "$STRESS_WORKERS" "$INTERVAL_MS" "$BACKEND" "$ACTIVE_PREFIX"

export LATENCY_WEIGHT
export BACKGROUND_WEIGHT
export BATCH_WEIGHT
export EULERPILOT_LATENCY_WEIGHT="$LATENCY_WEIGHT"
export EULERPILOT_BACKGROUND_WEIGHT="$BACKGROUND_WEIGHT"
export EULERPILOT_BATCH_WEIGHT="$BATCH_WEIGHT"
export EULERPILOT_CPU_PSI_THRESHOLD
export EULERPILOT_LATENCY_WAIT_THRESHOLD_NS
export EULERPILOT_BACKGROUND_RUNTIME_THRESHOLD_NS
export INTERVAL_MS
export STRESS_WORKERS
export WRK_THREADS
export WRK_CONNECTIONS
export WRK_DURATION
export BACKEND
export ACTIVE_PREFIX

exec "$ROOT/bench/nginx/run_nginx_stress_benchmark.sh"
